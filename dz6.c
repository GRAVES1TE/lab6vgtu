#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <math.h>
#include <locale.h>

/*
    Домашнее задание к лабораторной работе 6 (Вариант 21)
    Проверка принадлежности точки (x, y) заштрихованной треугольной области.

    Вершины треугольника:
    A(3, 5), B(3, -5), C(7, 0)

    Уравнения граничных прямых:
    1) Левая вертикальная граница: x = 3
    2) Верхняя наклонная граница AC: y = -1.25 * x + 8.75
    3) Нижняя наклонная граница BC: y = 1.25 * x - 8.75

    Условие принадлежности:
    x >= 3.0 && x <= 7.0 && y <= (-1.25 * x + 8.75) && y >= (1.25 * x - 8.75)
    (эквивалентно: x >= 3.0 && x <= 7.0 && fabs(y) <= 1.25 * (7.0 - x))

    Контрольные примеры:
    - Точка (4.0, 0.0)   — внутри области
    - Точка (5.0, 1.0)   — внутри области
    - Точка (3.0, 5.0)   — на границе (принадлежит)
    - Точка (7.0, 0.0)   — на границе (принадлежит)
    - Точка (2.0, 0.0)   — вне области (x < 3)
    - Точка (8.0, 0.0)   — вне области (x > 7)
    - Точка (4.0, 4.0)   — вне области (y выше границы)
*/

int main(void)
{
    setlocale(LC_ALL, "RUS");
    setlocale(LC_NUMERIC, "C");

    double x, y;

    printf("Введите координаты точки (x, y): ");
    if (scanf("%lf %lf", &x, &y) != 2)
    {
        printf("Ошибка: некорректный ввод координат.\n");
        return 1;
    }

    if (x >= 3.0 && x <= 7.0 && y <= (-1.25 * x + 8.75) && y >= (1.25 * x - 8.75))
    {
        printf("Точка (%.2lf, %.2lf) принадлежит закрашенной области\n", x, y);
    }
    else
    {
        printf("Точка (%.2lf, %.2lf) не принадлежит закрашенной области\n", x, y);
    }

    return 0;
}
